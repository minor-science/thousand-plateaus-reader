"""Build the French-term lexicon for plateaus 12-13 from the glosses in both variorums.

    python3 build_lexicon.py   -> lexicon_12_13.md

A term enters the lexicon where it is glossed in bold italics (***term*** [gloss]) in Column 4.
Regenerate after new rows or swaps; do not edit the output by hand.
"""
import re, unicodedata
from pathlib import Path
HERE = Path(__file__).parent
SRC = [("12", HERE / "nomadology" / "variorum_nomadology.md", r"^\| 12¶(\d+) "),
       ("13", HERE / "variorum_from_rtf.md", r"^\| ¶(\d+) ")]
GL = re.compile(r'\*\*\*([^*]+)\*\*\*\s*<span style="color:green">\[(.*?)\]</span>')

def key(t):
    t = unicodedata.normalize("NFD", t.lower())
    return re.sub(r"[^a-z0-9 ]", "", "".join(c for c in t if unicodedata.category(c) != "Mn")).strip()

entries = {}
for plat, path, rx in SRC:
    for line in path.read_text().splitlines():
        m = re.match(rx, line)
        if not m:
            continue
        n = int(m.group(1))
        col4 = re.split(r"(?<!\\)\|", line[2:-2])[3]
        for term, gloss in GL.findall(col4):
            term = term.strip()
            e = entries.setdefault(key(term), {"term": term, "gloss": gloss.strip(), "where": [], "massumi": None})
            e["where"].append(f"{plat}¶{n}")
            mm = re.search(r'Massumi:?\s*(?:keeps\s*)?"([^"]+)"', gloss)
            if mm and not e["massumi"]:
                e["massumi"] = mm.group(1)

rows = sorted(entries.values(), key=lambda e: key(e["term"]))
out = ["# French-term lexicon, plateaus 12-13",
       "",
       f"Generated by `build_lexicon.py` from the glosses in both variorums: {len(rows)} terms. Each term is glossed once, where it first appears; later rows use plain italics. Massumi's rendering is given where a gloss records it. Drafted automatically under the method in apparatus_of_capture_prompt.md; not yet reviewed.",
       "",
       "| French | Gloss | Massumi | Glossed at |",
       "|---|---|---|---|"]
for e in rows:
    gloss = re.sub(r'\s*;?\s*Massumi:?[^;\]]*', "", e["gloss"]).strip(" ;–—") or e["gloss"]
    out.append(f"| *{e['term']}* | {gloss.replace('|', chr(92)+'|')} | {e['massumi'] or ''} | {', '.join(dict.fromkeys(e['where']))} |")
(HERE / "lexicon_12_13.md").write_text("\n".join(out) + "\n")
print(len(rows), "terms;", sum(1 for e in rows if e["massumi"]), "with Massumi's rendering;",
      sum(1 for e in rows if any(w.startswith('12') for w in e['where'])), "from 12,",
      sum(1 for e in rows if any(w.startswith('13') for w in e['where'])), "from 13")
